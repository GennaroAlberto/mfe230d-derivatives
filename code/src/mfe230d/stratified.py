# Conditional Monte Carlo: the variance path of the Heston model, and the mixing formula
# ---------------------------------------------------------------------------------------

def cir_exact(v0, kappa, theta, xi, t, n_paths: int, seed=None, rng=None) -> np.ndarray:
    """Exact samples of dV = kappa (theta - V) dt + xi sqrt(V) dW at the grid t (t[0] = 0).

    V_{t+h} = c chi'^2_d(lambda) with c = xi^2 (1 - e^{-kappa h}) / (4 kappa), d = 4 kappa theta / xi^2
    and lambda = V_t e^{-kappa h} / c (Glasserman 2003, Section 3.4.1). Shape (n_paths, len(t)).
    """
    rng = _rng(seed, rng)
    t = np.asarray(t, dtype=float)
    V = np.empty((int(n_paths), t.size))
    V[:, 0] = v0
    d = 4.0 * kappa * theta / xi**2
    for k, h in enumerate(np.diff(t)):
        e = np.exp(-kappa * h)
        c = xi**2 * (1.0 - e) / (4.0 * kappa)
        V[:, k + 1] = c * rng.noncentral_chisquare(d, V[:, k] * e / c)
    return V


def heston_variance_integrals(V, t, kappa, theta, xi):
    """Q = int_0^T V dt (trapezoidal rule on the grid) and I = int_0^T sqrt(V) dW, recovered from
    the variance equation: I = (V_T - V_0 - kappa theta T + kappa Q) / xi (Willard; Broadie--Kaya)."""
    t = np.asarray(t, dtype=float)
    Q = np.sum(0.5 * (V[:, 1:] + V[:, :-1]) * np.diff(t), axis=1)
    T = t[-1] - t[0]
    I = (V[:, -1] - V[:, 0] - kappa * theta * T + kappa * Q) / xi
    return Q, I


def mixing_parameters(S, T, rho, Q, I):
    """Modified spot S~ = S exp(rho I - rho^2 Q / 2) and volatility sigma~ = sqrt((1 - rho^2) Q / T)."""
    Q, I = np.asarray(Q, dtype=float), np.asarray(I, dtype=float)
    return S * np.exp(rho * I - 0.5 * rho**2 * Q), np.sqrt(np.maximum(1.0 - rho**2, 0.0) * Q / T)


def bs_conditional(kind, S_tilde, K, T, r, y, sig_tilde):
    """Black--Scholes call or put at spot S~ and volatility sigma~ (arrays), with sigma~ = 0 allowed:
    then the price is the discounted intrinsic value of the forward S~ e^{(r-y)T}."""
    S_tilde, sig = np.broadcast_arrays(np.asarray(S_tilde, dtype=float), np.asarray(sig_tilde, dtype=float))
    out = np.empty(S_tilde.shape)
    pos = sig > 0
    f = call if kind == "call" else put
    out[pos] = f(S_tilde[pos], K, T, r, y, sig[pos])
    fwd = S_tilde[~pos] * np.exp((r - y) * T)
    intrinsic = np.maximum(fwd - K, 0.0) if kind == "call" else np.maximum(K - fwd, 0.0)
    out[~pos] = np.exp(-r * T) * intrinsic
    return out


def heston_put_samples(S, K, T, r, y, rho, v0, kappa, theta, xi, m: int = 64, n: int = 10_000,
                       seed=None, rng=None) -> dict:
    """Plain and conditional samples of the discounted Heston put on the same variance paths.

    The variance is sampled exactly at m equal steps (``cir_exact``); Q and I come from
    ``heston_variance_integrals``. The plain sample draws one more normal N per path,
    S_T = S~ exp((r - y - sigma~^2/2) T + sigma~ sqrt(T) N); the conditional sample is the
    Black--Scholes put at (S~, sigma~), its exact conditional expectation given the variance path
    (Proposition st-mixing). Both estimate the same (discretised) price.

    ``rho`` may be a number or a sequence; for a sequence the result maps each rho to its dict,
    all computed on the same variance paths and the same normals N (the variance path does not
    depend on rho), so the output for one rho is the same as a separate call with that rho.
    """
    rng = _rng(seed, rng)
    t = time_grid(T, m)
    V = cir_exact(v0, kappa, theta, xi, t, n, rng=rng)
    Q, I = heston_variance_integrals(V, t, kappa, theta, xi)
    N = rng.standard_normal(n)

    def one(rho_):
        St, sg = mixing_parameters(S, T, rho_, Q, I)
        ST = St * np.exp((r - y - 0.5 * sg**2) * T + sg * np.sqrt(T) * N)
        plain = np.exp(-r * T) * np.maximum(K - ST, 0.0)
        cond = bs_conditional("put", St, K, T, r, y, sg)
        return dict(plain=plain, conditional=cond, Q=Q, I=I, S_tilde=St, sigma_tilde=sg)

    if np.ndim(rho) == 0:
        return one(float(rho))
    return {float(x): one(float(x)) for x in rho}


def log_euler_mixing_check(S, K, T, r, y, rho, variance_path, m: int, n: int, seed=None, kind="put"):
    """Proposition st-mixing (iv) on a grid: log-Euler paths driven by (W, W_perp) against the
    conditional estimator built from the same W.

    ``variance_path(W_increments, t)`` returns V at the left end points t_0..t_{m-1} as a function of
    the increments of W only. Returns the plain payoffs and the conditional values per path.
    """
    rng = np.random.default_rng(seed)
    t = time_grid(T, m)
    dt = np.diff(t)
    dW = rng.standard_normal((n, m)) * np.sqrt(dt)
    dB = rng.standard_normal((n, m)) * np.sqrt(dt)
    V = variance_path(dW, t)
    sv = np.sqrt(V)
    lnS = np.log(S) + np.sum((r - y - 0.5 * V) * dt + sv * (rho * dW + np.sqrt(1 - rho**2) * dB), axis=1)
    ST = np.exp(lnS)
    pay = np.maximum(K - ST, 0.0) if kind == "put" else np.maximum(ST - K, 0.0)
    Q, I = np.sum(V * dt, axis=1), np.sum(sv * dW, axis=1)
    St, sg = mixing_parameters(S, T, rho, Q, I)
    return dict(plain=np.exp(-r * T) * pay, conditional=bs_conditional(kind, St, K, T, r, y, sg))


def mixing_laboratory(S, K, T, r, y, rhos=(0.0, -0.3, -0.7, -0.9), m: int = 64, n: int = 100_000,
                      seed: int = 19, params=None) -> dict:
    """Standard errors of the plain and conditional Heston put estimators, for several rho.

    Returns {rho: dict(plain=(mean, se), conditional=(mean, se), ratio=se_c / se_p)}; all rho use
    the same seed, hence the same variance paths and normals.
    """
    P = dict(HESTON_LAB if params is None else params)
    out = {}
    samples = heston_put_samples(S, K, T, r, y, tuple(rhos), P["v0"], P["kappa"], P["theta"], P["xi"], m=m, n=n,
                                 seed=seed)
    for rho in rhos:
        s = samples[float(rho)]
        a, b = s["plain"], s["conditional"]
        sa, sb = a.std(ddof=1) / np.sqrt(n), b.std(ddof=1) / np.sqrt(n)
        out[rho] = dict(plain=(float(a.mean()), float(sa)), conditional=(float(b.mean()), float(sb)),
                        ratio=float(sb / sa))
    return out


