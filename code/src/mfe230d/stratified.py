def terminal_price(z, S, T, r, y, sigma):
    """S_T = S exp(nu T + sigma sqrt(T) z), nu = r - y - sigma^2/2."""
    return S * np.exp((r - y - 0.5 * sigma**2) * T + sigma * np.sqrt(T) * np.asarray(z, dtype=float))


def discounted_call(z, S, K, T, r, y, sigma):
    """e^{-rT} (S_T - K)^+ as a function of the normal draw z."""
    return np.exp(-r * T) * np.maximum(terminal_price(z, S, T, r, y, sigma) - K, 0.0)


def stratified_normals(counts, seed=None, rng=None):
    """Normals stratified by inversion: counts[h] draws of Z given Z in (N^{-1}(h/H), N^{-1}((h+1)/H)]."""
    u, lab = stratified_uniforms(counts, seed=seed, rng=rng)
    return norm_inv(u), lab


def stratified_call(S, K, T, r, y, sigma, H: int, n: int, seed=None, rng=None) -> dict:
    """Call price from n draws in H equiprobable strata of Z with proportional allocation."""
    counts = proportional_allocation(n, np.full(H, 1.0 / H))
    z, lab = stratified_normals(counts, seed=seed, rng=rng)
    return stratified_estimate(discounted_call(z, S, K, T, r, y, sigma), lab, np.full(H, 1.0 / H))


def course_otm_experiment(strata=(10, 50, 100), n: int = 100_000, reps: int = 100, seed: int = 5,
                          params=None) -> dict:
    """The course notebook's experiment: ``reps`` independent prices of the deep out-of-the-money
    call from n draws, plain and with H equiprobable strata (proportional allocation).

    Returns, for "plain" and each H, the mean of the prices, their variance (divisor reps, as
    in the notebook) and the exact variance of one estimate, sigma^2 / n or sum p_h sigma_h^2 / n.
    """
    P = dict(COURSE_OTM if params is None else params)
    rng = np.random.default_rng(seed)
    f = lambda z: discounted_call(z, P["S"], P["K"], P["T"], P["r"], P["y"], P["sigma"])
    zs = (np.log(P["K"] / P["S"]) - (P["r"] - P["y"] - 0.5 * P["sigma"] ** 2) * P["T"]) / (P["sigma"] * np.sqrt(P["T"]))
    out = {}
    prices = np.array([f(rng.standard_normal(n)).mean() for _ in range(reps)])
    _, _, v1 = stratum_moments(f, np.array([-np.inf, np.inf]), kinks=(zs,))
    out["plain"] = dict(mean=float(prices.mean()), var=float(prices.var()), exact_var=float(v1[0]) / n)
    for H in strata:
        prices = np.array([stratified_call(P["S"], P["K"], P["T"], P["r"], P["y"], P["sigma"], H, n, rng=rng)["mean"]
                           for _ in range(reps)])
        p, m, v = stratum_moments(f, normal_edges(H), kinks=(zs,))
        out[H] = dict(mean=float(prices.mean()), var=float(prices.var()), exact_var=float(np.sum(p * v)) / n)
    out["price"] = float(call(**P))
    return out


