"""Stratified sampling, Latin hypercube sampling and conditional Monte Carlo (Chapter 10).

Stratification. The sample space of one uniform U (equivalently of one normal Z = N^{-1}(U)) is
cut into H strata ((h-1)/H, h/H] or, more generally, into intervals with edges ``edges``; a
stratum of probability p_h receives n_h draws from the conditional law, generated by inversion
(U = a + (b - a) V). The stratified estimator is sum_h p_h * (mean of stratum h). The module
implements proportional and Neyman allocation, the estimator with its standard error,
post-stratification, and exact within-stratum means and variances of a function of one normal
(Gauss--Legendre on each finite stratum, so that narrow strata lose no precision to cancellation).

Paths. The first normal of the Brownian-bridge construction of ``paths.gbm_paths`` sets W_T, so
stratifying that normal stratifies the terminal value and the bridge fills in the rest; the same
idea for any unit vector v gives ``stratified_projection``. ``latin_hypercube`` builds Latin
hypercube samples from random permutations.

Conditioning. ``cir_exact`` samples a square-root variance process exactly on a grid
(noncentral chi-square transitions); ``heston_put_samples`` returns, on the same variance
paths, the plain estimator of a put in the Heston model (one extra normal per path) and the
conditional (mixing) estimator, the Black--Scholes put with the modified spot and volatility of
the notes.

Every sampler takes a ``seed`` (anything ``numpy.random.default_rng`` accepts) or a ``rng``.
Every method of the chapter is implemented here from scratch; ``bs.py`` supplies the
Black--Scholes closed forms, ``rng.norm_inv`` the inverse normal distribution function of
Chapter 5 and ``paths.gbm_paths`` the path constructions of Chapter 7.
"""
