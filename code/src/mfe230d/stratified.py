def stratified_projection(v, xi, seed=None, rng=None) -> np.ndarray:
    """Normal vectors Z = v xi + (I - v v^T) Z' with Z' ~ N(0, I) independent of the given xi.

    If xi has the conditional law of v^T Z given v^T Z in a stratum (v a unit vector), the rows
    have the conditional law of Z given that event (Proposition st-bridge (i)).
    """
    v = np.asarray(v, dtype=float)
    v = v / np.linalg.norm(v)
    xi = np.asarray(xi, dtype=float)
    Zp = _rng(seed, rng).standard_normal((xi.size, v.size))
    return Zp - np.outer(Zp @ v, v) + np.outer(xi, v)


def linear_direction(t, w=None) -> np.ndarray:
    """Unit vector v with v^T Z proportional to sum_j w_j W_{t_j}, for the increments construction.

    On the grid as_grid(t) the increments construction is W = L Z with L_ij = sqrt(Delta_j) for
    j <= i, so sum_j w_j W_{t_j} = (L^T w)^T Z. With w = (0, ..., 0, 1) this is W_T; with
    w = (1, ..., 1) it is the sum of the path over the dates (the exponent of a geometric average).
    """
    t = np.asarray(t, dtype=float)
    t = t if t[0] == 0 else np.concatenate([[0.0], t])
    m = t.size - 1
    w = np.ones(m) if w is None else np.asarray(w, dtype=float)
    L = np.tril(np.ones((m, m))) * np.sqrt(np.diff(t))[None, :]
    v = L.T @ w
    return v / np.linalg.norm(v)


def terminal_stratified_normals(counts, m: int, seed=None, rng=None):
    """Normals of shape (sum(counts), m) whose first column is stratified (counts[h] per stratum).

    Fed to ``paths.gbm_paths(..., method="bridge")``, the first column sets W_T: the paths are
    stratified on their terminal value and completed by the Brownian bridge. With
    method="increments" the same normals stratify only the first increment.
    """
    rng = _rng(seed, rng)
    z1, lab = stratified_normals(counts, rng=rng)
    Z = rng.standard_normal((z1.size, m))
    Z[:, 0] = z1
    return Z, lab


def latin_hypercube(n: int, d: int, seed=None, rng=None) -> np.ndarray:
    """Latin hypercube sample of n points in (0, 1)^d: V_ij = (pi_j(i) + U_ij) / n.

    pi_1, ..., pi_d are independent uniform random permutations of {0, ..., n-1} and the U_ij
    are i.i.d. uniforms on (0, 1): each column has exactly one point in each [k/n, (k+1)/n).
    """
    rng = _rng(seed, rng)
    perms = np.argsort(rng.random((d, n)), axis=1).T  # column j is a uniform random permutation
    return (perms + open_uniforms(rng, (n, d))) / n


def asian_call_values(Z, S, K, T, r, y, sigma, method: str = "increments"):
    """Discounted arithmetic Asian call e^{-rT} (mean_j S_{t_j} - K)^+ with t_j = j T / m, j = 1..m.

    ``Z`` has shape (n, m); ``method`` is the construction of the Brownian path ("increments",
    "bridge" or "pca", as in paths.gbm_paths).
    """
    Z = np.atleast_2d(Z)
    St = gbm_paths(S, time_grid(T, Z.shape[1]), r, y, sigma, Z=Z, method=method)[:, 1:]
    return np.exp(-r * T) * np.maximum(St.mean(axis=1) - K, 0.0)


def asian_laboratory(S, K, T, r, y, sigma, m: int = 12, n: int = 2**16, H: int = 64, lhs_n: int = 2**10,
                     lhs_reps: int = 2000, n_sd: int = 2**20, seed: int = 10) -> dict:
    """Arithmetic Asian call: plain, terminal stratification (bridge), first-increment
    stratification, post-stratification on W_T, stratification of the direction of
    sum_j W_{t_j} (``linear_direction``), and Latin hypercube (increments and bridge).

    Each method uses n paths (proportional allocation, n/H per stratum). The plain standard
    error at n paths is sd / sqrt(n), with the plain standard deviation per path ``sd`` estimated
    from a separate plain run of ``n_sd`` paths. Latin hypercube uses ``lhs_reps`` independent
    designs of ``lhs_n`` points; its standard error at n paths is sd(replicates) sqrt(lhs_n / n),
    and ``ratio_se`` is the standard error of its standard-error ratio, ratio / sqrt(2 (reps - 1)).
    Returns dicts with ``mean``, ``se`` (and ``sd`` for "plain").
    """
    rng = np.random.default_rng(seed)
    f = lambda Z, meth: asian_call_values(Z, S, K, T, r, y, sigma, meth)
    p = np.full(H, 1.0 / H)
    counts = proportional_allocation(n, p)
    out = {}
    sd = float(np.std(f(rng.standard_normal((n_sd, m)), "increments"), ddof=1))
    v = f(rng.standard_normal((n, m)), "increments")
    out["plain"] = dict(mean=float(v.mean()), se=sd / np.sqrt(n), sd=sd)
    Z, lab = terminal_stratified_normals(counts, m, rng=rng)
    out["terminal (bridge)"] = stratified_estimate(f(Z, "bridge"), lab, p)
    Z, lab = terminal_stratified_normals(counts, m, rng=rng)
    out["first increment"] = stratified_estimate(f(Z, "increments"), lab, p)
    Z = rng.standard_normal((n, m))
    lab = strata_of(ndtr(Z[:, 0]), equiprobable_edges(H))
    out["post-stratified W_T"] = poststratified_estimate(f(Z, "bridge"), lab, p)
    xi, lab = stratified_normals(counts, rng=rng)
    Z = stratified_projection(linear_direction(time_grid(T, m)), xi, rng=rng)
    out["average direction"] = stratified_estimate(f(Z, "increments"), lab, p)
    for meth in ("increments", "bridge"):
        reps = np.array([f(norm_inv(latin_hypercube(lhs_n, m, rng=rng)), meth).mean() for _ in range(lhs_reps)])
        se = float(reps.std(ddof=1) * np.sqrt(lhs_n / n))
        out[f"LHS ({meth})"] = dict(mean=float(reps.mean()), se=se,
                                    se_of_mean=float(reps.std(ddof=1) / np.sqrt(lhs_reps)),
                                    ratio_se=se / (sd / np.sqrt(n)) / np.sqrt(2.0 * (lhs_reps - 1)))
    return out


def geometric_asian_call(S, K, T, r, y, sigma, m: int):
    """Discounted call on the geometric average of S at t_j = j T / m, in closed form (the control)."""
    t = time_grid(T, m)[1:]
    mg = np.log(S) + (r - y - 0.5 * sigma**2) * t.mean()
    vg = sigma**2 * np.minimum.outer(t, t).sum() / m**2
    sd = np.sqrt(vg)
    return float(np.exp(-r * T) * (np.exp(mg + 0.5 * vg) * ndtr((mg + vg - np.log(K)) / sd)
                                   - K * ndtr((mg - np.log(K)) / sd)))


def asian_reference(S, K, T, r, y, sigma, m: int = 12, n: int = 2**22, n_pilot: int = 2**16, seed: int = 2026,
                    chunk: int = 2**20) -> dict:
    """High-accuracy reference for the arithmetic Asian call: a geometric-average control variate,
    with the coefficient estimated on an independent pilot run (so the estimator is unbiased).
    Returns the estimate, its standard error and the coefficient."""
    rng = np.random.default_rng(seed)
    D = np.exp(-r * T)

    def both(k):
        St = gbm_paths(S, time_grid(T, m), r, y, sigma, Z=rng.standard_normal((k, m)))[:, 1:]
        return D * np.maximum(St.mean(axis=1) - K, 0.0), D * np.maximum(np.exp(np.log(St).mean(axis=1)) - K, 0.0)

    Yp, Xp = both(n_pilot)
    beta = float(np.cov(Yp, Xp)[0, 1] / np.var(Xp, ddof=1))
    s1 = s2 = 0.0
    done = 0
    while done < n:
        k = min(chunk, n - done)
        Y, X = both(k)
        R = Y - beta * X
        s1 += R.sum(); s2 += (R * R).sum(); done += k
    mean = s1 / n
    var = (s2 - n * mean * mean) / (n - 1)
    return dict(mean=float(mean + beta * geometric_asian_call(S, K, T, r, y, sigma, m)),
                se=float(np.sqrt(var / n)), beta=beta)


