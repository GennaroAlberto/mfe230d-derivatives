def _ratio_row(est, plain_se, exact=None):
    return dict(mean=float(est["mean"]), se=float(est["se"]), ratio=float(est["se"] / plain_se),
                exact=None if exact is None else float(exact))


def laboratory(seed: int = 10, n_call: int = 200_000, n_otm: int = 100_000, n_asian: int = 2**16,
               H_asian: int = 64, lhs_n: int = 2**10, lhs_reps: int = 2000, n_sd: int = 2**20,
               n_heston: int = 400_000) -> dict:
    """Every number of the chapter's laboratory table, from one seed.

    Standard-error ratios to plain Monte Carlo at equal n. ``ratio`` is the method's standard
    error from the run divided by the plain standard error at the same n: sigma / sqrt(n) with
    the exact sigma (by quadrature) for the one-dimensional calls, the plain standard deviation
    from a separate run of ``n_sd`` paths for the Asian rows, and the plain estimator on the same
    variance paths for the Heston rows. ``exact`` is the value of the
    theorems (stratum variances by quadrature) where one is available.
    """
    from .bs import TEST_CASE
    rng = np.random.default_rng(seed)
    rows = {}
    # 1. one-dimensional: the test-case call and the course's deep out-of-the-money call
    for tag, P, n, Hs in (("call", TEST_CASE, n_call, (10, 100)), ("otm", COURSE_OTM, n_otm, (10, 100))):
        S, K, T, r, y, sig = (P[k] for k in ("S", "K", "T", "r", "y", "sigma"))
        f = lambda z: discounted_call(z, S, K, T, r, y, sig)
        zs = (np.log(K / S) - (r - y - 0.5 * sig**2) * T) / (sig * np.sqrt(T))
        x = f(rng.standard_normal(n))
        _, _, v1 = stratum_moments(f, np.array([-np.inf, np.inf]), kinks=(zs,))
        plain_se = np.sqrt(v1[0] / n)
        rows[(tag, "plain")] = dict(mean=float(x.mean()), se=float(x.std(ddof=1) / np.sqrt(n)),
                                    ratio=float(x.std(ddof=1) / np.sqrt(n) / plain_se), exact=1.0)
        for H in Hs:
            p, m, v = stratum_moments(f, normal_edges(H), kinks=(zs,))
            fac = allocation_factors(p, m, v)
            rows[(tag, f"proportional {H}")] = _ratio_row(stratified_call(S, K, T, r, y, sig, H, n, rng=rng),
                                                         plain_se, np.sqrt(fac["proportional"]))
            if tag == "call" and H == 10:
                counts = neyman_allocation(n, p, np.sqrt(v), minimum=2)
                z, lab = stratified_normals(counts, rng=rng)
                rows[(tag, f"neyman {H}")] = _ratio_row(stratified_estimate(f(z), lab, p), plain_se,
                                                        np.sqrt(fac["neyman"]))
                z = rng.standard_normal(n)
                lab = strata_of(ndtr(z), equiprobable_edges(H))
                rows[(tag, f"post {H}")] = _ratio_row(poststratified_estimate(f(z), lab, p), plain_se,
                                                      np.sqrt(fac["proportional"]))
    # 2. the arithmetic Asian call on 12 monthly fixings
    P = TEST_CASE
    a = asian_laboratory(P["S"], P["K"], P["T"], P["r"], P["y"], P["sigma"], m=12, n=n_asian, H=H_asian,
                         lhs_n=lhs_n, lhs_reps=lhs_reps, n_sd=n_sd, seed=int(rng.integers(2**31)))
    for k, v in a.items():
        rows[("asian", k)] = _ratio_row(v, a["plain"]["se"])
        if "ratio_se" in v:
            rows[("asian", k)]["ratio_se"] = v["ratio_se"]
    # 3. the Heston put: conditional (mixing) estimator against plain
    mix = mixing_laboratory(P["S"], P["K"], P["T"], P["r"], P["y"], rhos=(0.0, -0.7), n=n_heston,
                            seed=int(rng.integers(2**31)))
    for rho, v in mix.items():
        rows[("heston", f"plain {rho}")] = dict(mean=v["plain"][0], se=v["plain"][1], ratio=1.0, exact=None)
        rows[("heston", f"conditional {rho}")] = dict(mean=v["conditional"][0], se=v["conditional"][1],
                                                     ratio=v["ratio"], exact=None)
    return rows


def laboratory_costs(reps: int = 7, seed: int = 0) -> dict:
    """Cost of each method of the laboratory relative to its plain estimator: median wall-clock
    time of the whole estimator (generation, payoff, estimate) over ``reps`` runs.

    The plain estimators use NumPy's normal generator (and the increments construction for the
    Asian call). These ratios depend on the machine and its load; they are not pinned by tests.
    """
    import time
    from .bs import TEST_CASE

    def med(fn):
        ts = []
        for _ in range(reps):
            t0 = time.perf_counter(); fn(); ts.append(time.perf_counter() - t0)
        return float(np.median(ts))

    rng = np.random.default_rng(seed)
    P = TEST_CASE
    S, K, T, r, y, sig = (P[k] for k in ("S", "K", "T", "r", "y", "sigma"))
    f = lambda z: discounted_call(z, S, K, T, r, y, sig)
    n = 2**18
    out = {}
    plain_est = lambda x: (x.mean(), x.std(ddof=1) / np.sqrt(x.size))
    base = med(lambda: plain_est(f(rng.standard_normal(n))))
    for H in (10, 100):
        out[("call", f"proportional {H}")] = med(lambda: stratified_call(S, K, T, r, y, sig, H, n, rng=rng)) / base
    p, m, v = stratum_moments(f, normal_edges(10), kinks=(0.15,))
    counts = neyman_allocation(n, p, np.sqrt(v), minimum=2)
    out[("call", "neyman 10")] = med(lambda: (lambda zl: stratified_estimate(f(zl[0]), zl[1], p))(
        stratified_normals(counts, rng=rng))) / base
    p10 = np.full(10, 0.1)
    out[("call", "post 10")] = med(lambda: (lambda z: poststratified_estimate(
        f(z), strata_of(ndtr(z), equiprobable_edges(10)), p10))(rng.standard_normal(n))) / base
    m_ = 12
    g = lambda Z, meth: asian_call_values(Z, S, K, T, r, y, sig, meth)
    na, H = 2**16, 64
    pH = np.full(H, 1.0 / H)
    cnt = proportional_allocation(na, pH)
    vdir = linear_direction(time_grid(T, m_))
    base = med(lambda: plain_est(g(rng.standard_normal((na, m_)), "increments")))

    def term(meth):
        Z, lab = terminal_stratified_normals(cnt, m_, rng=rng)
        return stratified_estimate(g(Z, meth), lab, pH)

    def post():
        Z = rng.standard_normal((na, m_))
        return poststratified_estimate(g(Z, "bridge"), strata_of(ndtr(Z[:, 0]), equiprobable_edges(H)), pH)

    def proj():
        xi, lab = stratified_normals(cnt, rng=rng)
        return stratified_estimate(g(stratified_projection(vdir, xi, rng=rng), "increments"), lab, pH)

    def lhs(meth, nl=2**10):
        return [g(norm_inv(latin_hypercube(nl, m_, rng=rng)), meth).mean() for _ in range(na // nl)]

    for key, fn in (("terminal (bridge)", lambda: term("bridge")), ("first increment", lambda: term("increments")),
                    ("post-stratified W_T", post), ("average direction", proj),
                    ("LHS (increments)", lambda: lhs("increments")), ("LHS (bridge)", lambda: lhs("bridge"))):
        out[("asian", key)] = med(fn) / base
    return out
