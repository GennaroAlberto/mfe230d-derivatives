def _rng(seed=None, rng=None):
    return rng if rng is not None else np.random.default_rng(seed)


# ---------------------------------------------------------------------------------------
# Uniforms in strata, allocations, the stratified and post-stratified estimators
# ---------------------------------------------------------------------------------------

def open_uniforms(rng, size) -> np.ndarray:
    """Uniforms on the open interval (0, 1): (k + 1/2) 2^-53 with k uniform on {0, ..., 2^53 - 1}.

    Strata are filled by u = a + (b - a) v; with v never 0 or 1, u never hits a stratum edge,
    so N^{-1}(u) is finite even in the first and last strata.
    """
    k = rng.integers(0, 2**53, size=size, dtype=np.int64)
    return (k.astype(float) + 0.5) * 2.0**-53


def equiprobable_edges(H: int) -> np.ndarray:
    """Edges 0, 1/H, ..., 1 of H equiprobable strata of a uniform."""
    return np.linspace(0.0, 1.0, int(H) + 1)


def stratified_uniforms(counts, edges=None, seed=None, rng=None):
    """counts[h] uniforms in each stratum (edges[h], edges[h+1]] of (0, 1).

    ``edges`` defaults to equiprobable strata. Returns (u, labels): u has sum(counts) entries,
    stratum by stratum, and labels[i] is the stratum of u[i]. Strata with counts[h] = 0 are
    simply empty (the caller decides whether that biases the estimator).
    """
    counts = np.asarray(counts, dtype=int)
    if np.any(counts < 0):
        raise ValueError("counts must be nonnegative")
    edges = equiprobable_edges(counts.size) if edges is None else np.asarray(edges, dtype=float)
    if edges.size != counts.size + 1:
        raise ValueError("need len(edges) = len(counts) + 1")
    labels = np.repeat(np.arange(counts.size), counts)
    v = open_uniforms(_rng(seed, rng), labels.size)
    lo, hi = edges[labels], edges[labels + 1]
    return lo + (hi - lo) * v, labels


def _largest_remainder(total: int, weights) -> np.ndarray:
    """Integers n_h >= 0 summing to ``total`` with n_h close to total * w_h / sum(w)."""
    w = np.asarray(weights, dtype=float)
    target = total * w / w.sum()
    n = np.floor(target).astype(int)
    short = total - n.sum()
    if short > 0:
        n[np.argsort(-(target - n), kind="stable")[:short]] += 1
    return n


def proportional_allocation(n: int, p) -> np.ndarray:
    """n_h = n p_h, rounded by largest remainders so that sum n_h = n (exact if every n p_h is an integer)."""
    return _largest_remainder(int(n), p)


def neyman_allocation(n: int, p, sd, minimum: int = 1) -> np.ndarray:
    """Neyman allocation n_h proportional to p_h sigma_h, with at least ``minimum`` draws per stratum.

    Each stratum of positive probability first receives ``minimum`` draws (a stratum with
    sigma_h = 0 needs one draw to learn its mean, and the standard error needs two per stratum);
    the remaining n - H * minimum draws are split in proportion to p_h sigma_h by largest
    remainders. If every sigma_h is 0, the remainder is split proportionally to p_h.
    """
    p, sd = np.asarray(p, dtype=float), np.asarray(sd, dtype=float)
    rest = int(n) - minimum * p.size
    if rest < 0:
        raise ValueError("n is smaller than minimum * number of strata")
    w = p * sd
    return minimum + _largest_remainder(rest, w if w.sum() > 0 else p)


def stratified_estimate(values, labels, p) -> dict:
    """Stratified estimator sum_h p_h Ybar_h from samples ``values`` with stratum ``labels``.

    Returns the estimate ``mean``, the standard error ``se`` = sqrt(sum_h p_h^2 s_h^2 / n_h)
    (s_h the sample standard deviation in stratum h, which needs n_h >= 2: ``se`` is NaN if some
    stratum has fewer than two draws), the counts and the stratum means and variances. Strata of
    probability zero are ignored; a stratum of positive probability without draws raises.
    """
    v, lab, p = np.asarray(values, dtype=float), np.asarray(labels, dtype=int), np.asarray(p, dtype=float)
    H = p.size
    n_h = np.bincount(lab, minlength=H)
    live = p > 0
    if np.any(live & (n_h == 0)):
        raise ValueError("a stratum of positive probability has no draws: the estimator would be biased")
    s1 = np.bincount(lab, weights=v, minlength=H)
    m_h = np.divide(s1, n_h, out=np.zeros(H), where=n_h > 0)
    dev = v - m_h[lab]
    ss = np.bincount(lab, weights=dev * dev, minlength=H)
    var_h = np.divide(ss, n_h - 1, out=np.full(H, np.nan), where=n_h > 1)
    mean = float(np.sum(p[live] * m_h[live]))
    if np.all(n_h[live] >= 2):
        se = float(np.sqrt(np.sum(p[live] ** 2 * var_h[live] / n_h[live])))
    else:
        se = float("nan")
    return dict(mean=mean, se=se, n=int(n_h.sum()), n_h=n_h, mean_h=m_h, var_h=var_h)


def strata_of(u, edges) -> np.ndarray:
    """Stratum index h of each u, for strata (edges[h], edges[h+1]] (u = edges[0] goes to stratum 0)."""
    edges = np.asarray(edges, dtype=float)
    return np.clip(np.searchsorted(edges, u, side="left") - 1, 0, edges.size - 2)


def poststratified_estimate(values, labels, p) -> dict:
    """Post-stratified estimator sum_h p_h Ybar_h from an ordinary i.i.d. sample.

    The stratum counts N_h are random. If some stratum of positive probability is empty, the
    estimator falls back to the plain sample mean (``fallback`` True), as in the notes. The
    standard error is the plug-in sqrt(sum_h p_h^2 s_h^2 / N_h) when every N_h >= 2, and NaN
    otherwise.
    """
    v, lab, p = np.asarray(values, dtype=float), np.asarray(labels, dtype=int), np.asarray(p, dtype=float)
    n_h = np.bincount(lab, minlength=p.size)
    if np.any((p > 0) & (n_h == 0)):
        return dict(mean=float(v.mean()), se=float("nan"), n=v.size, n_h=n_h, fallback=True)
    out = stratified_estimate(v, lab, p)
    out["fallback"] = False
    return out


def inverse_count_moment(n: int, p: float) -> float:
    """E[1/N ; N >= 1] for N ~ Binomial(n, p), summed exactly over the binomial law."""
    from scipy.stats import binom
    k = np.arange(1, n + 1)
    return float(np.sum(binom.pmf(k, n, p) / k))


def poststratified_mse(n: int, p, var_h) -> float:
    """sum_h p_h^2 sigma_h^2 E[1/N_h ; N_h >= 1]: the mean squared error of post-stratification
    up to terms of order max_h (1 - p_h)^n (the event that some stratum is empty)."""
    p, var_h = np.asarray(p, dtype=float), np.asarray(var_h, dtype=float)
    return float(sum(ph * ph * vh * inverse_count_moment(n, ph) for ph, vh in zip(p, var_h)))


def replicate(estimator, reps: int, seed=None) -> dict:
    """Run ``estimator(rng)`` (returning a number) ``reps`` times with one generator.

    Returns the mean of the replicates, their sample standard deviation ``sd`` and the standard
    error ``se`` = sd / sqrt(reps) of the mean: the error estimate for methods whose draws are
    dependent (Latin hypercube) or with one draw per stratum.
    """
    rng = np.random.default_rng(seed)
    x = np.array([estimator(rng) for _ in range(int(reps))], dtype=float)
    return dict(mean=float(x.mean()), sd=float(x.std(ddof=1)), se=float(x.std(ddof=1) / np.sqrt(x.size)),
                values=x)


# ---------------------------------------------------------------------------------------
# Exact within-stratum moments of a function of one standard normal
# ---------------------------------------------------------------------------------------

def _phi(z):
    return np.exp(-0.5 * z * z) / np.sqrt(2.0 * np.pi)


def stratum_moments(g, z_edges, kinks=(), nodes: int = 24):
    """Probabilities p_h, means mu_h and variances sigma_h^2 of g(Z) given Z in (z_h, z_{h+1}].

    ``g`` is a vectorised function of z and ``z_edges`` increasing (the end points may be
    -inf, inf). Finite strata are integrated by Gauss--Legendre with ``nodes`` points on each
    piece between consecutive kinks of g (pass the kinks!), and the variance is computed from
    the centred integrand, so narrow strata keep full precision; infinite strata use adaptive
    quadrature. Strata of zero probability get mean and variance 0.
    """
    z_edges = np.asarray(z_edges, dtype=float)
    H = z_edges.size - 1
    p = ndtr(z_edges[1:]) - ndtr(z_edges[:-1])
    mu, var = np.zeros(H), np.zeros(H)
    x, w = roots_legendre(nodes)
    finite = np.flatnonzero(np.isfinite(z_edges[:-1]) & np.isfinite(z_edges[1:]))
    if finite.size:
        a, b = z_edges[finite], z_edges[finite + 1]
        # split each stratum at the kinks inside it: pieces (a, k1), (k1, k2), ..., (km, b)
        ks = np.sort(np.asarray(kinks, dtype=float))
        cuts = [a] + [np.clip(k, a, b) for k in ks] + [b]
        Z, Wt = [], []
        for lo, hi in zip(cuts[:-1], cuts[1:]):
            half = 0.5 * (hi - lo)
            Z.append(0.5 * (hi + lo)[:, None] + half[:, None] * x[None, :])
            Wt.append(half[:, None] * w[None, :])
        Z, Wt = np.hstack(Z), np.hstack(Wt)
        dens = Wt * _phi(Z)
        mass = dens.sum(axis=1)
        G = g(Z)
        ok = mass > 0
        m = np.divide((dens * G).sum(axis=1), mass, out=np.zeros(finite.size), where=ok)
        v = np.divide((dens * (G - m[:, None]) ** 2).sum(axis=1), mass, out=np.zeros(finite.size), where=ok)
        mu[finite], var[finite] = m, v
    for h in np.flatnonzero(~(np.isfinite(z_edges[:-1]) & np.isfinite(z_edges[1:]))):
        lo, hi = z_edges[h], z_edges[h + 1]
        if p[h] <= 0:
            continue
        lo_q, hi_q = max(lo, -40.0), min(hi, 40.0)
        pts = [k for k in kinks if lo_q < k < hi_q]
        f1 = lambda u: float(g(np.array([u]))[0]) * _phi(u)
        m = integrate.quad(f1, lo_q, hi_q, points=pts or None, limit=400, epsabs=0, epsrel=1e-12)[0] / p[h]
        f2 = lambda u: (float(g(np.array([u]))[0]) - m) ** 2 * _phi(u)
        v = integrate.quad(f2, lo_q, hi_q, points=pts or None, limit=400, epsabs=0, epsrel=1e-12)[0] / p[h]
        mu[h], var[h] = m, v
    return p, mu, var


def call_stratum_moments(z_edges, S, K, T, r, y, sigma):
    """Closed-form p_h, mu_h, sigma_h^2 of the discounted call e^{-rT}(S_T - K)^+ on Z-strata.

    With s = sigma sqrt(T), F = S e^{(r-y)T}, S_T = F e^{-s^2/2 + sZ} and c = max(a, z*):
    E[X 1{a<Z<=b}] = e^{-rT} [F (N(b-s) - N(c-s)) - K (N(b) - N(c))], and similarly for X^2.
    Subject to cancellation in very narrow strata: use ``stratum_moments`` there.
    """
    z_edges = np.asarray(z_edges, dtype=float)
    s, F, D = sigma * np.sqrt(T), S * np.exp((r - y) * T), np.exp(-r * T)
    zs = (np.log(K / S) - (r - y - 0.5 * sigma**2) * T) / s
    a, b = z_edges[:-1], z_edges[1:]
    c = np.minimum(np.maximum(a, zs), b)
    dN = lambda shift: ndtr(b - shift) - ndtr(c - shift)
    p = ndtr(b) - ndtr(a)
    m1 = D * (F * dN(s) - K * dN(0.0))
    m2 = D * D * (F * F * np.exp(s * s) * dN(2 * s) - 2 * K * F * dN(s) + K * K * dN(0.0))
    mu = np.divide(m1, p, out=np.zeros_like(p), where=p > 0)
    var = np.divide(m2, p, out=np.zeros_like(p), where=p > 0) - mu * mu
    return p, mu, np.maximum(var, 0.0)


def variance_decomposition(p, mu_h, var_h) -> dict:
    """sigma^2 = within + between: sum p_h sigma_h^2 and sum p_h (mu_h - mu)^2."""
    p, mu_h, var_h = (np.asarray(a, dtype=float) for a in (p, mu_h, var_h))
    mu = float(np.sum(p * mu_h))
    within, between = float(np.sum(p * var_h)), float(np.sum(p * (mu_h - mu) ** 2))
    return dict(mean=mu, within=within, between=between, total=within + between)


def allocation_factors(p, mu_h, var_h) -> dict:
    """Variance factors against plain Monte Carlo at equal n (n Var / sigma^2).

    ``proportional`` = sum p_h sigma_h^2 / sigma^2 and ``neyman`` = (sum p_h sigma_h)^2 / sigma^2,
    the values of Theorem st-variance and Proposition st-optimal (real-valued allocations).
    """
    dec = variance_decomposition(p, mu_h, var_h)
    sd = np.sqrt(np.asarray(var_h, dtype=float))
    return dict(proportional=dec["within"] / dec["total"],
                neyman=float(np.sum(np.asarray(p) * sd)) ** 2 / dec["total"], total=dec["total"])


def normal_edges(H: int) -> np.ndarray:
    """Edges N^{-1}(h / H), h = 0..H, of H equiprobable strata of a standard normal."""
    from scipy.special import ndtri
    return ndtri(equiprobable_edges(H))


